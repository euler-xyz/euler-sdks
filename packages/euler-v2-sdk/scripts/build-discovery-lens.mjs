// Compiles contracts/AccountDiscoveryLens.sol and regenerates the committed
// bytecode artifact used by the onchain account-vaults discovery adapter.
//
// Usage: node scripts/build-discovery-lens.mjs   (requires `solc` on PATH)
//
// The adapter never deploys this contract; it performs an eth_call with no
// `to` address and `data = creationCode ++ abi.encode(ctor args)`. The
// constructor returns the discovery result directly. See the .sol for details.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const src = join(root, 'contracts', 'AccountDiscoveryLens.sol')
const out = join(
  root,
  'src/services/accountService/adapters/accountVaultsOnchainAdapter/generated/accountDiscoveryLens.ts',
)

const combined = execFileSync(
  'solc',
  ['--optimize', '--optimize-runs', '200', '--combined-json', 'bin,abi', src],
  { encoding: 'utf8' },
)
const parsed = JSON.parse(combined)
const key = Object.keys(parsed.contracts).find((k) => k.endsWith(':AccountDiscoveryLens'))
if (!key) throw new Error('AccountDiscoveryLens not found in solc output')
const { bin } = parsed.contracts[key]
const solcVersion = execFileSync('solc', ['--version'], { encoding: 'utf8' })
  .split('\n')
  .find((l) => l.startsWith('Version'))
  ?.trim()

mkdirSync(dirname(out), { recursive: true })
const banner = `// AUTO-GENERATED by scripts/build-discovery-lens.mjs — do not edit by hand.
// Source: contracts/AccountDiscoveryLens.sol
// Compiler: ${solcVersion} (optimize, runs=200)
// Regenerate with: node scripts/build-discovery-lens.mjs
`
writeFileSync(
  out,
  `${banner}
import type { Hex } from "viem";

/** Creation bytecode of AccountDiscoveryLens. Deployless-lens usage: perform an
 *  eth_call with no \`to\` and \`data = ACCOUNT_DISCOVERY_LENS_BYTECODE ++
 *  abi.encode(owner, subAccountIds, vaults, evc)\`; the constructor returns
 *  \`(address[][] deposits, address[][] borrows)\`. */
export const ACCOUNT_DISCOVERY_LENS_BYTECODE: Hex = "0x${bin}";
`,
)
console.log(`Wrote ${out} (${bin.length / 2} bytes bytecode, ${solcVersion})`)

// Sanity check for the reader of this script.
const written = readFileSync(out, 'utf8')
if (!written.includes('0x' + bin)) throw new Error('artifact verification failed')
